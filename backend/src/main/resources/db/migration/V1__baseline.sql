-- Baseline schema per spec/data-model.md (sections 4–6).

CREATE SEQUENCE ticket_public_seq START WITH 1001 INCREMENT BY 1;

CREATE TABLE tickets (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id           VARCHAR(20)  NOT NULL,
    title               VARCHAR(120) NOT NULL,
    description         VARCHAR(5000) NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    priority            VARCHAR(20)  NOT NULL DEFAULT 'MEDIUM',
    assignee            VARCHAR(100),
    category            VARCHAR(30)  NOT NULL,
    resolution_notes    VARCHAR(2000),
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_tickets PRIMARY KEY (id),
    CONSTRAINT uq_tickets_public_id UNIQUE (public_id),
    CONSTRAINT ck_tickets_public_id_format CHECK (public_id LIKE 'TKT-%'),
    CONSTRAINT ck_tickets_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_tickets_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_tickets_title_not_blank CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT ck_tickets_description_not_blank CHECK (LENGTH(TRIM(description)) > 0),
    CONSTRAINT ck_tickets_category_not_blank CHECK (LENGTH(TRIM(category)) > 0),
    CONSTRAINT ck_tickets_assignee_not_blank CHECK (assignee IS NULL OR LENGTH(TRIM(assignee)) > 0),
    CONSTRAINT ck_tickets_resolution_notes CHECK (
        (status IN ('RESOLVED', 'CLOSED')
            AND resolution_notes IS NOT NULL
            AND LENGTH(TRIM(resolution_notes)) > 0)
        OR (status IN ('OPEN', 'IN_PROGRESS', 'CANCELLED') AND resolution_notes IS NULL)
    )
);

CREATE INDEX ix_tickets_updated_at ON tickets (updated_at DESC, id DESC);
CREATE INDEX ix_tickets_status_updated_at ON tickets (status, updated_at DESC, id DESC);

CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ticket_id   BIGINT       NOT NULL,
    author      VARCHAR(100) NOT NULL,
    content     VARCHAR(2000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_comments PRIMARY KEY (id),
    CONSTRAINT fk_comments_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_comments_author_not_blank CHECK (LENGTH(TRIM(author)) > 0),
    CONSTRAINT ck_comments_content_not_blank CHECK (LENGTH(TRIM(content)) > 0)
);

CREATE INDEX ix_comments_ticket_created ON comments (ticket_id, created_at, id);

CREATE TABLE ticket_ingestion (
    ticket_id           BIGINT       NOT NULL,
    status              VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    requested_version   BIGINT       NOT NULL,
    indexed_version     BIGINT,
    attempt_count       INTEGER      NOT NULL DEFAULT 0,
    requested_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_attempt_at     TIMESTAMP WITH TIME ZONE,
    indexed_at          TIMESTAMP WITH TIME ZONE,
    last_error          VARCHAR(500),
    CONSTRAINT pk_ticket_ingestion PRIMARY KEY (ticket_id),
    CONSTRAINT fk_ticket_ingestion_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE RESTRICT,
    CONSTRAINT ck_ticket_ingestion_status CHECK (status IN ('PENDING', 'INDEXED', 'FAILED')),
    CONSTRAINT ck_ticket_ingestion_attempts CHECK (attempt_count >= 0)
);

CREATE INDEX ix_ticket_ingestion_due ON ticket_ingestion (status, next_attempt_at);
CREATE INDEX ix_ticket_ingestion_requested ON ticket_ingestion (status, requested_at);